package com.freevibe.data.legal

import com.freevibe.data.model.ContentSource

data class ProviderDisclosure(
    val source: ContentSource,
    val displayName: String,
    val content: String,
    val status: ProviderStatus,
    val termsUrl: String,
    val licenseSummary: String,
    val attribution: String,
    val cachePolicy: String,
    val userActions: String,
    val storeDisclosure: String,
)

enum class ProviderStatus(val label: String) {
    ACTIVE("Active"),
    LEGACY("Legacy"),
    LOCAL("Local"),
    COMMUNITY("Community"),
    GENERATED("Generated"),
}

data class ProviderRuntimeControl(
    val source: ContentSource,
    val surfaces: String,
    val status: ProviderRuntimeControlStatus,
    val currentControl: String,
    val disabledBehavior: String,
    val followUp: String,
)

enum class ProviderRuntimeControlStatus(val label: String) {
    COVERED("Covered"),
    PARTIAL("Partial"),
    MISSING("Missing"),
    NOT_APPLICABLE("Not applicable"),
}

